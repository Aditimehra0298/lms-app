import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import {
  assertCertificateOwnerOrAdmin,
  assertCertificateReleasedToLearner,
  isMainAdminRequest,
} from "@/lib/server/certificate-access";
import { readCertificatePdfBuffer } from "@/lib/server/certificate-pdf-store";
import { ensureCertificatePdfReady, waitForArchivedCertificatePdf } from "@/lib/server/n8n-certificate-service";
import {
  isN8nCertificateProviderConfigured,
  mayUseLocalCertificateFallback,
  officialCertificatePdfMinBytes,
} from "@/lib/server/certificate-generation-policy";

export const dynamic = "force-dynamic";
export const maxDuration = 120;

type Params = { params: Promise<{ id: string }> };

/**
 * One-shot learner download: prepare (n8n once if needed) → return PDF bytes.
 * Requires owner session or admin session (POC-D-01).
 */
export async function POST(request: Request, { params }: Params) {
  const { id } = await params;
  if (!id?.trim()) {
    return NextResponse.json({ ok: false, message: "Missing certificate id" }, { status: 400 });
  }

  const certificateId = id.trim();
  const row = await prisma.lmsCertificate.findUnique({ where: { id: certificateId } });
  if (!row) {
    return NextResponse.json({ ok: false, message: "Certificate not found." }, { status: 404 });
  }

  const denied = assertCertificateOwnerOrAdmin(request, row.learnerEmail);
  if (denied) return denied;
  const notReleased = assertCertificateReleasedToLearner(request, row);
  if (notReleased) return notReleased;
  const isAdmin = isMainAdminRequest(request);

  let body: { forceRegenerate?: boolean; attachment?: boolean } = {};
  const contentType = request.headers.get("content-type") ?? "";
  try {
    if (contentType.includes("application/json")) {
      body = (await request.json()) as typeof body;
    } else if (
      contentType.includes("application/x-www-form-urlencoded") ||
      contentType.includes("multipart/form-data")
    ) {
      const form = await request.formData();
      const attachmentRaw = form.get("attachment");
      body = {
        forceRegenerate: form.get("forceRegenerate") === "true",
        attachment: attachmentRaw !== "false" && attachmentRaw !== "0",
      };
    } else if (contentType.trim()) {
      return NextResponse.json({ ok: false, message: "Unsupported content type" }, { status: 415 });
    }
  } catch {
    return NextResponse.json({ ok: false, message: "Invalid request body" }, { status: 400 });
  }

  const email = row.learnerEmail.trim().toLowerCase();
  const attachment = body.attachment !== false;
  if (!isAdmin) body.forceRegenerate = false;

  try {
    const prepared = await ensureCertificatePdfReady({
      certificateId,
      learnerEmail: email,
      forceRegenerate: body.forceRegenerate === true,
    });

    if (!prepared.ok) {
      const mayUseLocal = mayUseLocalCertificateFallback(isN8nCertificateProviderConfigured());
      if (mayUseLocal) {
        const { ensureLocalCertificatePdf } = await import("@/lib/server/local-certificate-fallback");
        const localOk = await ensureLocalCertificatePdf(certificateId).catch(() => false);
        if (!localOk) {
          const httpStatus =
            prepared.status === "awaiting_approval"
              ? 403
              : prepared.status === "pending"
                ? 202
                : 409;
          return NextResponse.json(prepared, { status: httpStatus });
        }
      } else {
        const httpStatus =
          prepared.status === "awaiting_approval"
            ? 403
            : prepared.status === "pending"
              ? 202
              : 409;
        return NextResponse.json(prepared, { status: httpStatus });
      }
    }

    const fresh = await prisma.lmsCertificate.findUnique({
      where: { id: certificateId },
      select: { issuedVia: true, certificateNumber: true },
    });
    const via = fresh?.issuedVia ?? row.issuedVia;
    const minBytes = officialCertificatePdfMinBytes(via);

    let buffer = await readCertificatePdfBuffer(certificateId, { minBytes });

    if (!buffer) {
      await waitForArchivedCertificatePdf(certificateId, isAdmin ? 60_000 : 30_000);
      buffer = await readCertificatePdfBuffer(certificateId, { minBytes });
    }

    if (!buffer && isAdmin) {
      // Admin preview safety net: build course-template overlay when n8n PDF is not back yet.
      const { ensureLocalCertificatePdf } = await import("@/lib/server/local-certificate-fallback");
      const localOk = await ensureLocalCertificatePdf(certificateId).catch(() => false);
      if (localOk) {
        buffer = await readCertificatePdfBuffer(certificateId, { minBytes: 128 });
      }
    }

    if (!buffer) {
      return NextResponse.json(
        {
          ok: false,
          status: "pending",
          message:
            prepared.ok === false
              ? prepared.message
              : "Certificate PDF is still being generated by n8n. Wait a minute and try View PDF again.",
          n8nCalled: prepared.ok ? prepared.n8nCalled : false,
        },
        { status: 202 },
      );
    }

    const filename = `${(fresh?.certificateNumber ?? row.certificateNumber ?? certificateId).replace(/[^\w.-]+/g, "_")}.pdf`;

    return new Response(new Uint8Array(buffer), {
      status: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Length": String(buffer.length),
        "Cache-Control": "private, no-store",
        "Content-Disposition": `${attachment ? "attachment" : "inline"}; filename="${filename}"`,
        "X-Certificate-Cached": prepared.cached ? "1" : "0",
      },
    });
  } catch (err) {
    console.error("[certificates/download]", err);
    return NextResponse.json(
      { ok: false, message: "Could not download certificate. Please try again." },
      { status: 503 },
    );
  }
}
